// Copies ABIs and bytecode from Hardhat's artifacts into the web app. Run after `pnpm compile`.
import { readFileSync, writeFileSync } from "node:fs";
const pick = (name) => { const a = JSON.parse(readFileSync(`artifacts/contracts/${name}.sol/${name}.json`, "utf8")); return { abi: a.abi, bytecode: a.bytecode }; };
const out = { MockRupee: pick("MockRupee"), KuriCircle: pick("KuriCircle"), KuriFactory: pick("KuriFactory") };
writeFileSync("web/src/chain/artifacts.ts", "// Generated by tools/export-abi.mjs from the compiled contracts. Do not edit.\n" +
  Object.entries(out).map(([k, v]) => `export const ${k} = { abi: ${JSON.stringify(v.abi)} as const, bytecode: ${JSON.stringify(v.bytecode)} as \`0x\${string}\` };`).join("\n") + "\n");
console.log("exported", Object.keys(out).join(", "));
